"""PostgreSQL schema bootstrap and row insertion helpers for the Cerebro note/review data model."""
from __future__ import annotations
from datetime import date, datetime, timedelta
import json

from app.model.postgresdb_schema import Note, NoteSection, ReviewHistory, MasteryStage
from app.client.db.pg_client import PostgreSQLClient
from app.logging_config import setup_logging
from app.clock import today

logger = setup_logging()

DEFAULT_SCHEMA_MIGRATIONS = [
    """
    -- 1. Main Notes Table (File-level metadata)
    CREATE TABLE IF NOT EXISTS notes (
        note_id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        file_path        TEXT NOT NULL UNIQUE,
        title            TEXT NOT NULL,
        topic            TEXT NOT NULL,
        tags             TEXT[] NOT NULL DEFAULT '{}',
        created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        status           TEXT NOT NULL DEFAULT 'active'
    );

    -- 2. Subtopics Table (Section-level spaced repetition)
    CREATE TABLE IF NOT EXISTS note_sections (
        section_id       INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        note_id          INTEGER NOT NULL REFERENCES notes (note_id) ON DELETE CASCADE,
        heading          TEXT NOT NULL,
        content          TEXT,
        review_stage     TEXT NOT NULL DEFAULT 'novice',
        mastery_score    REAL NOT NULL DEFAULT 0.1,
        next_review_date DATE NOT NULL,
        last_reviewed_at TIMESTAMP,
        review_count     INTEGER NOT NULL DEFAULT 0,
        embedding        REAL[] NOT NULL DEFAULT '{}',
        embedding_model  TEXT,
        embedding_dimensions INTEGER,
        interval_days    INTEGER NOT NULL DEFAULT 1,
        source_hash      TEXT,
        created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(note_id, heading)
    );

    -- 3. Review History Log Table
    CREATE TABLE IF NOT EXISTS review_history (
        review_id        INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        note_id          INTEGER NOT NULL REFERENCES notes (note_id) ON DELETE CASCADE,
        section_id       INTEGER REFERENCES note_sections (section_id) ON DELETE SET NULL,
        review_date      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        score            INTEGER,
        user_answer      TEXT,
        llm_feedback     TEXT
    );
    ALTER TABLE notes ALTER COLUMN tags SET DEFAULT '{}';
    UPDATE notes SET tags='{}' WHERE tags IS NULL;
    ALTER TABLE notes ALTER COLUMN tags SET NOT NULL;
    ALTER TABLE note_sections ALTER COLUMN embedding SET DEFAULT '{}';
    UPDATE note_sections SET embedding='{}' WHERE embedding IS NULL;
    ALTER TABLE note_sections ALTER COLUMN embedding SET NOT NULL;
    ALTER TABLE note_sections ADD COLUMN IF NOT EXISTS interval_days INTEGER NOT NULL DEFAULT 1;
    ALTER TABLE note_sections ADD COLUMN IF NOT EXISTS source_hash TEXT;
    ALTER TABLE note_sections ADD COLUMN IF NOT EXISTS embedding_model TEXT;
    ALTER TABLE note_sections ADD COLUMN IF NOT EXISTS embedding_dimensions INTEGER;
    CREATE INDEX IF NOT EXISTS note_sections_due_idx ON note_sections(next_review_date);
    CREATE INDEX IF NOT EXISTS review_history_section_date_idx ON review_history(section_id, review_date DESC);
    CREATE TABLE IF NOT EXISTS generated_questions (
        question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        section_id INTEGER NOT NULL REFERENCES note_sections(section_id) ON DELETE CASCADE,
        question_type TEXT NOT NULL CHECK (question_type IN ('mcq','msq','seq')),
        payload JSONB NOT NULL,
        generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        active BOOLEAN NOT NULL DEFAULT TRUE
    );
    CREATE INDEX IF NOT EXISTS generated_questions_section_idx ON generated_questions(section_id, active);
    CREATE TABLE IF NOT EXISTS review_sessions (
        session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        telegram_user_id BIGINT NOT NULL,
        section_id INTEGER NOT NULL REFERENCES note_sections(section_id) ON DELETE CASCADE,
        started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        completed_at TIMESTAMP,
        satisfied BOOLEAN,
        score INTEGER,
        overview TEXT
    );
    CREATE TABLE IF NOT EXISTS review_answers (
        answer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        session_id BIGINT NOT NULL REFERENCES review_sessions(session_id) ON DELETE CASCADE,
        question_id BIGINT REFERENCES generated_questions(question_id) ON DELETE SET NULL,
        question TEXT NOT NULL,
        user_answer TEXT,
        reference_answer TEXT NOT NULL,
        satisfied BOOLEAN NOT NULL,
        feedback TEXT,
        answered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS telegram_users (
        telegram_user_id BIGINT PRIMARY KEY,
        chat_id BIGINT NOT NULL,
        username TEXT,
        first_name TEXT,
        active BOOLEAN NOT NULL DEFAULT TRUE,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    """,
]

class NoteRepository:
    def __init__(self, db: PostgreSQLClient | None = None):
        self.db = db or PostgreSQLClient()
        self.db.migrate(DEFAULT_SCHEMA_MIGRATIONS)

    def add_note(self, note: Note) -> int | None:
        """Add a note to the PostgreSQL database."""
        logger.info(f"\nAdding note with details {note}")
        values = {
            "file_path": note.file_path,
            "title": note.title,
            "topic": note.topic,
            "tags": note.tags,
            "created_at": note.created_at,
            "updated_at": note.updated_at,
            "status": note.status,
        }
        if note.id is not None:
            values["note_id"] = note.id
        with self.db.transaction() as cursor:
            cursor.execute(
                """INSERT INTO notes (file_path,title,topic,tags,created_at,updated_at,status)
                VALUES (%s,%s,%s,%s,%s,%s,%s)
                ON CONFLICT (file_path) DO UPDATE SET title=EXCLUDED.title, topic=EXCLUDED.topic,
                tags=EXCLUDED.tags, updated_at=EXCLUDED.updated_at
                RETURNING note_id""",
                (note.file_path, note.title, note.topic, note.tags, note.created_at, note.updated_at, note.status),
            )
            row = cursor.fetchone()
            return row["note_id"] if row else None

    def update_note_metadata(self, note_id: int, *, title: str, topic: str, tags: list[str]) -> None:
        self.db.update("notes", {"title": title, "topic": topic, "tags": tags, "updated_at": datetime.now()},
                       "note_id = %s", (note_id,))

    def add_section(self, section: NoteSection) -> int | None:
        """Add or insert a note section (subtopic) into the database."""
        logger.info(f"\nAdding section '{section.heading}' for note ID {section.note_id}")
        values = {
            "note_id": section.note_id,
            "heading": section.heading,
            "content": section.content,
            "review_stage": section.review_stage.value if hasattr(section.review_stage, 'value') else section.review_stage,
            "mastery_score": section.mastery_score,
            "next_review_date": section.next_review_date,
            "last_reviewed_at": section.last_reviewed_at,
            "review_count": section.review_count,
            "embedding": section.embedding,
            "embedding_model": section.embedding_model,
            "embedding_dimensions": len(section.embedding),
            "updated_at": datetime.now(),
        }
        columns = list(values)
        placeholders = ",".join(["%s"] * len(columns))
        updates = ",".join(f"{key}=EXCLUDED.{key}" for key in (
            "content", "embedding", "embedding_model", "embedding_dimensions", "updated_at"
        ))
        with self.db.transaction() as cursor:
            cursor.execute(
                f"INSERT INTO note_sections ({','.join(columns)}) VALUES ({placeholders}) "
                f"ON CONFLICT (note_id,heading) DO UPDATE SET {updates} RETURNING section_id",
                list(values.values()),
            )
            row = cursor.fetchone()
            return row["section_id"] if row else None

    def update_section(self, section: NoteSection) -> None:
        """Update an existing note section."""
        logger.info(f"\nUpdating section '{section.heading}' (ID {section.section_id})")
        values = {
            "content": section.content,
            "review_stage": section.review_stage.value if hasattr(section.review_stage, 'value') else section.review_stage,
            "mastery_score": section.mastery_score,
            "next_review_date": section.next_review_date,
            "last_reviewed_at": section.last_reviewed_at,
            "review_count": section.review_count,
            "embedding": section.embedding,
            "embedding_model": section.embedding_model,
            "embedding_dimensions": len(section.embedding),
            "updated_at": datetime.now(),
        }
        self.db.update(
            table="note_sections",
            values=values,
            where="section_id = %s",
            params=(section.section_id,)
        )

    def fetch_sections_by_note_id(self, note_id: int) -> list[NoteSection]:
        """Fetch all sections for a given note."""
        logger.info("Fetching sections for note ID %s", note_id)
        rows = self.db.fetch_all(
            "SELECT * FROM note_sections WHERE note_id = %s",
            (note_id,)
        )
        return [NoteSection(**row) for row in rows]

    def add_review_history(self, review: ReviewHistory) -> dict[str, object] | None:
        """Insert a review history row into the review_history table."""
        logger.info(f"\nAdding review history with details {review}")
        values = {
            "note_id": review.note_id,
            "section_id": review.section_id,
            "review_date": review.review_date,
            "score": review.score,
            "user_answer": review.user_answer,
            "llm_feedback": review.llm_feedback,
        }
        if review.review_id is not None:
            values["review_id"] = review.review_id
        return self.db.insert(
            "review_history",
            values,
            returning="review_id",
        )

    def fetch_sections_to_review_for_specific_date(
        self, target_date: date | None = None,
    ) -> list[dict]:
        """Fetch all subtopics/sections scheduled for review on or before target_date (defaults to today)."""
        review_date = target_date or today()
        logger.info(f"\nFetching sections to review for specific date {review_date}")

        rows = self.db.fetch_all(
            """
            SELECT s.*, n.title as note_title, n.topic as note_topic, n.file_path
            FROM note_sections s
            JOIN notes n ON s.note_id = n.note_id
            WHERE s.next_review_date <= %s
            AND n.status = 'active'
            """,
            (review_date,)
        )
        return rows

    def update_section_after_review(
        self, section_id: int,
        score: int | None = None,
        user_answer: str | None = None,
        llm_feedback: str | None = None,
        satisfied: bool | None = None,
    ) -> None:
        """Update section stage, score, and next review date after a review, and log history."""
        logger.info("Updating section after review for section ID %s", section_id)
        section_dict = self.db.fetch_one(
            "SELECT * FROM note_sections WHERE section_id = %s",
            (section_id,)
        )
        if section_dict is None:
            raise ValueError(f"Section with ID {section_id} not found")

        current_stage = MasteryStage(section_dict["review_stage"])
        passed = satisfied if satisfied is not None else (score is not None and score >= 3)
        new_stage = current_stage.next_stage if passed else current_stage

        now = datetime.now()
        next_review = today() + timedelta(days=new_stage.interval_days if passed else 1)

        update_values = {
            "review_count": section_dict["review_count"] + 1,
            "review_stage": new_stage.value,
            "mastery_score": new_stage.stage_weight,
            "interval_days": new_stage.interval_days if passed else 1,
            "next_review_date": next_review,
            "last_reviewed_at": now,
            "updated_at": now,
        }

        with self.db.transaction() as cursor:
            sets = ", ".join(f"{column} = %s" for column in update_values)
            cursor.execute(
                f"UPDATE note_sections SET {sets} WHERE section_id = %s",
                [*update_values.values(), section_id],
            )
            cursor.execute(
                """INSERT INTO review_history
                (note_id, section_id, review_date, score, user_answer, llm_feedback)
                VALUES (%s, %s, %s, %s, %s, %s)""",
                (section_dict["note_id"], section_id, now, score, user_answer, llm_feedback),
            )

    def fetch_section(self, section_id: int) -> dict | None:
        return self.db.fetch_one(
            """SELECT s.*, n.title AS note_title, n.topic AS note_topic, n.file_path
            FROM note_sections s JOIN notes n ON n.note_id=s.note_id
            WHERE s.section_id=%s AND n.status='active'""", (section_id,)
        )

    def search_similar_sections(self, query_embedding: list[float], limit: int = 10) -> list[dict]:
        """Rank stored section vectors by cosine similarity."""
        import math
        rows = self.db.fetch_all(
            """SELECT s.section_id, s.heading, s.content, n.title AS note_title,
            n.file_path, s.embedding FROM note_sections s JOIN notes n ON n.note_id=s.note_id
            WHERE s.embedding IS NOT NULL AND n.status='active'"""
        )
        def cosine(vector: list[float] | None) -> float:
            if not vector or len(vector) != len(query_embedding):
                return -1.0
            dot = sum(a*b for a, b in zip(vector, query_embedding))
            norm_a = math.sqrt(sum(a*a for a in vector))
            norm_b = math.sqrt(sum(b*b for b in query_embedding))
            return dot / (norm_a * norm_b) if norm_a and norm_b else -1.0
        ranked = [{**row, "similarity": cosine(row.get("embedding"))} for row in rows]
        return sorted(ranked, key=lambda row: row["similarity"], reverse=True)[:max(0, limit)]

    def fetch_review_context(self, section_id: int, limit: int = 5) -> list[dict]:
        return self.db.fetch_all(
            """SELECT score, llm_feedback, review_date FROM review_history
            WHERE section_id=%s ORDER BY review_date DESC LIMIT %s""", (section_id, limit)
        )

    def replace_questions(self, section_id: int, questions: list[dict]) -> list[dict]:
        """Persist a generated question set and return its database identifiers."""
        saved = []
        with self.db.transaction() as cursor:
            cursor.execute("UPDATE generated_questions SET active=FALSE WHERE section_id=%s", (section_id,))
            for question in questions:
                cursor.execute(
                    """INSERT INTO generated_questions(section_id, question_type, payload)
                    VALUES (%s,%s,%s::jsonb) RETURNING question_id""",
                    (section_id, question["type"], json.dumps(question)),
                )
                row = cursor.fetchone()
                saved.append({**question, "question_id": row["question_id"]})
        return saved

    def create_session(self, telegram_user_id: int, section_id: int) -> int:
        result = self.db.insert("review_sessions", {
            "telegram_user_id": telegram_user_id, "section_id": section_id,
        }, returning="session_id")
        return int(result["session_id"])

    def add_session_answer(self, session_id: int, answer: dict) -> None:
        with self.db.transaction() as cursor:
            cursor.execute(
                """INSERT INTO review_answers
                (session_id, question_id, question, user_answer, reference_answer, satisfied, feedback)
                VALUES (%s,%s,%s,%s,%s,%s,%s)""",
                (session_id, answer.get("question_id"), answer["question"], answer.get("user_answer"),
                 answer["reference_answer"], answer["satisfied"], answer.get("feedback")),
            )

    def finish_session(self, session_id: int, *, satisfied: bool, score: int, overview: str) -> None:
        with self.db.transaction() as cursor:
            cursor.execute(
                "UPDATE review_sessions SET completed_at=%s, satisfied=%s, score=%s, overview=%s WHERE session_id=%s",
                (datetime.now(), satisfied, score, overview, session_id),
            )

    def complete_review_session(self, session_id: int, section_id: int, *, satisfied: bool,
                                score: int, overview: str, user_answer: str) -> None:
        """Commit session completion, section schedule, and review history together."""
        now = datetime.now()
        with self.db.transaction() as cursor:
            cursor.execute("SELECT * FROM note_sections WHERE section_id=%s FOR UPDATE", (section_id,))
            section = cursor.fetchone()
            if section is None:
                raise ValueError(f"Section with ID {section_id} not found")
            stage = MasteryStage(section["review_stage"])
            next_stage = stage.next_stage if satisfied else stage
            due = today() + timedelta(days=next_stage.interval_days if satisfied else 1)
            cursor.execute(
                """UPDATE note_sections SET review_count=review_count+1, review_stage=%s,
                mastery_score=%s, interval_days=%s, next_review_date=%s,
                last_reviewed_at=%s, updated_at=%s WHERE section_id=%s""",
                (next_stage.value, next_stage.stage_weight, next_stage.interval_days if satisfied else 1,
                 due, now, now, section_id),
            )
            cursor.execute(
                """INSERT INTO review_history(note_id,section_id,review_date,score,user_answer,llm_feedback)
                VALUES (%s,%s,%s,%s,%s,%s)""",
                (section["note_id"], section_id, now, score, user_answer, overview),
            )
            cursor.execute(
                """UPDATE review_sessions SET completed_at=%s,satisfied=%s,score=%s,overview=%s
                WHERE session_id=%s""", (now, satisfied, score, overview, session_id),
            )

    def register_telegram_user(self, user_id: int, chat_id: int, username: str | None, first_name: str | None) -> None:
        with self.db.transaction() as cursor:
            cursor.execute(
                """INSERT INTO telegram_users(telegram_user_id,chat_id,username,first_name)
                VALUES (%s,%s,%s,%s) ON CONFLICT (telegram_user_id) DO UPDATE SET
                chat_id=EXCLUDED.chat_id, username=EXCLUDED.username, first_name=EXCLUDED.first_name,
                active=TRUE, updated_at=CURRENT_TIMESTAMP""",
                (user_id, chat_id, username, first_name),
            )

    def fetch_telegram_users(self) -> list[dict]:
        return self.db.fetch_all("SELECT * FROM telegram_users WHERE active=TRUE")

    def _update_review_history(
        self, note_id: int,
        section_id: int | None = None,
        score: int | None = None,
        user_answer: str | None = None,
        llm_feedback: str | None = None,
    ) -> None:
        """Helper method to insert a row into review_history."""
        logger.info("Updating review history for note ID %s, section ID %s", note_id, section_id)
        review_history = ReviewHistory(
            note_id=note_id,
            section_id=section_id,
            review_date=datetime.now(),
            score=score,
            user_answer=user_answer,
            llm_feedback=llm_feedback,
        )
        self.add_review_history(review_history)

    def initialize_postgres_schema(self) -> PostgreSQLClient:
        """Create the Cerebro PostgreSQL tables if they do not already exist."""
        self.db.migrate(DEFAULT_SCHEMA_MIGRATIONS)
        return self.db

    def fetch_note_by_file_path(self, file_path: str) -> Note | None:
        """Fetch a note by its file path."""
        logger.info("Fetching note by file path %s", file_path)
        note_dict = self.db.fetch_one(
            "SELECT * FROM notes WHERE file_path = %s",
            (file_path,)
        )
        if note_dict is None:
            return None
        return Note(**note_dict)
